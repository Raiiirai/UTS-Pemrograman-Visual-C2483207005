private long bacaAngka(javax.swing.JTextField field, String namaInput) {

    String teks = field.getText().trim();

    if (teks.isEmpty()) {
        throw new IllegalArgumentException(
            namaInput + " wajib diisi."
        );
    }

    try {
        return Long.parseLong(teks);
    } catch (NumberFormatException e) {
        throw new IllegalArgumentException(
            namaInput + " harus berupa angka."
        );
    }
}

private long hitungTotalHarga() {

    if (txtNamaBarang.getText().trim().isEmpty()) {
        throw new IllegalArgumentException(
            "Nama barang wajib diisi."
        );
    }

    long harga = bacaAngka(txtHarga, "Harga satuan");
    long jumlah = bacaAngka(txtJumlah, "Jumlah pembelian");

    if (harga < 0) {
        throw new IllegalArgumentException(
            "Harga tidak boleh negatif."
        );
    }

    if (jumlah <= 0) {
        throw new IllegalArgumentException(
            "Jumlah pembelian harus lebih dari nol."
        );
    }

    try {
        return Math.multiplyExact(harga, jumlah);
    } catch (ArithmeticException e) {
        throw new IllegalArgumentException(
            "Total harga terlalu besar."
        );
    }
}

private String formatRupiah(long nominal) {

    NumberFormat format = NumberFormat.getIntegerInstance(
        new Locale("id", "ID")
    );

    return "Rp" + format.format(nominal);
}

