    private void btnBayarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBayarActionPerformed
        
try {
    long total = hitungTotalHarga();
    long pembayaran = bacaAngka(
        txtPembayaran,
        "Uang pembayaran"
    );
    if (pembayaran < 0) {
        throw new IllegalArgumentException(
            "Pembayaran tidak boleh negatif."
        );
    }
    txtTotal.setText(formatRupiah(total));
    if (pembayaran < total) {
        long kekurangan = total - pembayaran;

        txtKembalian.setText(
            "Kurang " + formatRupiah(kekurangan)
        );
        JOptionPane.showMessageDialog(
            this,
            "Pembayaran kurang "
            + formatRupiah(kekurangan),
            "Pembayaran Tidak Cukup",
            JOptionPane.WARNING_MESSAGE
        );
    } else {
        long kembalian = pembayaran - total;

        txtKembalian.setText(
            "Kembalian " + formatRupiah(kembalian)
        );

        JOptionPane.showMessageDialog(
            this,
            "Pembayaran berhasil!\nKembalian: "
            + formatRupiah(kembalian),
            "Transaksi Berhasil",
            JOptionPane.INFORMATION_MESSAGE
        );

    }

} catch (IllegalArgumentException e) {

    JOptionPane.showMessageDialog(
        this,
        e.getMessage(),
        "Input Tidak Valid",
        JOptionPane.ERROR_MESSAGE
    );

}

    }//GEN-LAST:event_btnBayarActionPerformed

